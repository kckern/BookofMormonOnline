/**
 * gen-utf8mb4-convert.mjs
 *
 * Emits backend/scripts/out/convert-utf8mb4.sql — the maintenance-window script that
 * standardizes the whole database onto utf8mb4 / utf8mb4_0900_ai_ci.
 * See docs/plans/2026-06-10-utf8mb4-standardization.md.
 *
 * READ-ONLY against the DB (information_schema + a HEX sample of the latin1 dictionary
 * to auto-pick true-latin1 vs double-encoded conversion). Does NOT execute any ALTER.
 * The operator runs the produced .sql in a window, app stopped, WITHOUT --force.
 */
import { getDb, closeDb } from '../src/data/db.js';
import { sql } from 'kysely';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const TARGET = 'utf8mb4 COLLATE utf8mb4_0900_ai_ci';
const TARGET_COLL = 'utf8mb4_0900_ai_ci';
const OUT_FILE = new URL('./out/convert-utf8mb4.sql', import.meta.url).pathname;
// Tables with bespoke handling — excluded from the blanket pass.
const SPECIAL = ['bom_xtras_dictionary', 'bom_xtras_stats'];

const db = getDb();
const SCHEMA = (await sql`SELECT DATABASE() AS db`.execute(db)).rows[0].db;

// ── 1. Tables needing a CONVERT (>=1 char column not already on target), small→large ──
const convertRows = (await sql`
  SELECT t.TABLE_NAME AS name, (t.DATA_LENGTH + t.INDEX_LENGTH) AS bytes
  FROM information_schema.TABLES t
  WHERE t.TABLE_SCHEMA = ${SCHEMA} AND t.ENGINE = 'InnoDB'
    AND t.TABLE_NAME IN (
      SELECT DISTINCT c.TABLE_NAME FROM information_schema.COLUMNS c
      WHERE c.TABLE_SCHEMA = ${SCHEMA} AND c.CHARACTER_SET_NAME IS NOT NULL
        AND c.COLLATION_NAME <> ${TARGET_COLL})
  ORDER BY bytes ASC`.execute(db)).rows
  .filter((r) => !SPECIAL.includes(r.name));

// ── 2. Tables with NO char columns but a non-target table default (cosmetic default fix) ──
const defaultOnlyRows = (await sql`
  SELECT t.TABLE_NAME AS name
  FROM information_schema.TABLES t
  WHERE t.TABLE_SCHEMA = ${SCHEMA} AND t.ENGINE = 'InnoDB'
    AND t.TABLE_COLLATION <> ${TARGET_COLL}
    AND t.TABLE_NAME NOT IN (
      SELECT DISTINCT c.TABLE_NAME FROM information_schema.COLUMNS c
      WHERE c.TABLE_SCHEMA = ${SCHEMA} AND c.CHARACTER_SET_NAME IS NOT NULL)
  ORDER BY t.TABLE_NAME`.execute(db)).rows
  .filter((r) => !SPECIAL.includes(r.name));

// ── 3. Decide the latin1 dictionary path by UTF-8 validity of the stored bytes ─────────
// Double-encoded (UTF-8 wrongly stored in a latin1 column) ⇒ every non-ASCII value is
// itself valid UTF-8, so a binary reinterpret recovers it cleanly. If ANY non-ASCII value
// is NOT valid UTF-8 (CONVERT(BINARY col USING utf8mb4) IS NULL), the binary trick would
// error mid-migration — so fall back to a plain latin1→utf8mb4 CONVERT, which is byte-
// lossless and can NEVER fail (every latin1 byte maps to a codepoint). Any pre-corrupted
// rows then carry the same cosmetic mojibake they already had; their ids are listed for
// optional manual cleanup after the window.
const dictCols = ['word', '_word', 'heading', 'content', 'string'];
const nonAscii = dictCols.map((c) => `\`${c}\` <> CONVERT(\`${c}\` USING ASCII)`).join(' OR ');
const invalidExpr = dictCols
  .map((c) => `(\`${c}\` <> CONVERT(\`${c}\` USING ASCII) AND CONVERT(BINARY \`${c}\` USING utf8mb4) IS NULL)`)
  .join(' OR ');
const dictStats = (await sql.raw(
  `SELECT COUNT(*) AS non_ascii_rows,
          COALESCE(SUM(${invalidExpr}), 0) AS invalid_utf8_rows,
          GROUP_CONCAT(id ORDER BY id) AS ids
   FROM bom_xtras_dictionary WHERE ${nonAscii}`,
).execute(db)).rows[0];
const nonAsciiRows = Number(dictStats.non_ascii_rows || 0);
const invalidRows = Number(dictStats.invalid_utf8_rows || 0);
const affectedIds = dictStats.ids || '';
// Only take the (risky) binary trick when the bytes are PROVABLY clean UTF-8 everywhere.
const doubleEncoded = nonAsciiRows > 0 && invalidRows === 0;

// ── 4. Emit ───────────────────────────────────────────────────────────────────────────
const out = [];
const P = (s) => out.push(s);
P('-- =====================================================================');
P('-- convert-utf8mb4.sql — standardize the DB to utf8mb4 / utf8mb4_0900_ai_ci');
P('-- Generated by backend/scripts/gen-utf8mb4-convert.mjs (read-only).');
P('-- Plan: docs/plans/2026-06-10-utf8mb4-standardization.md');
P('-- RUN IN A MAINTENANCE WINDOW, APP STOPPED, WITHOUT --force.');
P('-- Rehearse on a clone first. Rollback = restore the pre-window backup.');
P('-- =====================================================================');
P('SET NAMES utf8mb4;');
P('SET FOREIGN_KEY_CHECKS = 0;');
P('SET UNIQUE_CHECKS = 0;');
P(`ALTER DATABASE \`${SCHEMA}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;`);
P('');

P('-- --- Special case: bom_xtras_stats (empty) — varchar(1000) BTREE keys bust 3072B under mb4 ---');
P('ALTER TABLE bom_xtras_stats DROP INDEX `key`, DROP INDEX `value`;');
P(`ALTER TABLE bom_xtras_stats CONVERT TO CHARACTER SET ${TARGET};`);
P('ALTER TABLE bom_xtras_stats ADD INDEX `key` (`key`(191)), ADD INDEX `value` (`value`(191));');
P('');

P('-- --- Special case: bom_xtras_dictionary (latin1) ---');
P(`-- Inspected ${nonAsciiRows} non-ASCII rows; ${invalidRows} contain bytes that are NOT valid UTF-8.`);
if (affectedIds) P(`-- Affected ids (review after the window): ${affectedIds}`);
if (doubleEncoded) {
  P('-- Verdict: DOUBLE-ENCODED (all non-ASCII bytes are valid UTF-8) → binary-safe reinterpret.');
  P('ALTER TABLE bom_xtras_dictionary');
  P('  MODIFY word    VARBINARY(255),');
  P('  MODIFY _word   VARBINARY(255),');
  P('  MODIFY heading VARBINARY(255),');
  P('  MODIFY content BLOB,');
  P('  MODIFY string  BLOB;');
  P('ALTER TABLE bom_xtras_dictionary');
  P('  MODIFY word    VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NULL,');
  P('  MODIFY _word   VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL,');
  P('  MODIFY heading VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL,');
  P('  MODIFY content TEXT         CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NOT NULL,');
  P('  MODIFY string  TEXT         CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci NULL;');
  P(`ALTER TABLE bom_xtras_dictionary DEFAULT CHARACTER SET ${TARGET};`);
} else {
  P('-- Verdict: NOT cleanly double-encoded (some bytes are invalid UTF-8 / pre-corrupted).');
  P('-- Plain CONVERT chosen: byte-lossless, cannot fail. The affected rows above keep the');
  P('-- cosmetic mojibake they already had — re-import from the public-domain source if desired.');
  P(`ALTER TABLE bom_xtras_dictionary CONVERT TO CHARACTER SET ${TARGET};`);
}
P('');

P(`-- --- Blanket CONVERT: ${convertRows.length} tables, small→large ---`);
for (const r of convertRows) {
  const mb = (Number(r.bytes) / 1024 / 1024).toFixed(1);
  P(`ALTER TABLE \`${r.name}\` CONVERT TO CHARACTER SET ${TARGET};  -- ${mb} MB`);
}
P('');

if (defaultOnlyRows.length) {
  P(`-- --- Table-default-only fix: ${defaultOnlyRows.length} tables with no char columns ---`);
  for (const r of defaultOnlyRows) {
    P(`ALTER TABLE \`${r.name}\` DEFAULT CHARACTER SET ${TARGET};`);
  }
  P('');
}

P('SET FOREIGN_KEY_CHECKS = 1;');
P('SET UNIQUE_CHECKS = 1;');
P('-- ===================== END =====================');

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, out.join('\n') + '\n', 'utf8');

console.log('==================== SUMMARY ====================');
console.log(`schema              : ${SCHEMA}`);
console.log(`blanket CONVERT     : ${convertRows.length} tables`);
console.log(`default-only fix    : ${defaultOnlyRows.length} tables`);
console.log(`dictionary verdict  : ${doubleEncoded ? 'DOUBLE-ENCODED (binary trick)' : 'plain CONVERT (lossless)'}`);
console.log(`  non-ASCII rows=${nonAsciiRows}, invalid-utf8 rows=${invalidRows}, ids=${affectedIds}`);
console.log(`Wrote ${OUT_FILE}`);
await closeDb();
