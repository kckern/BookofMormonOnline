export type GeometryRow = {
  uid: number;
  version: string;
  verseId: number;
  page: number;
  imagePage: number;
  pageWidth: number;
  pageScale: number;
  X: number;
  Y: number;
  W: number;
  H: number;
  TLW: number;
  TLH: number;
  BRW: number;
  BRH: number;
};

export type Severity = 'error' | 'warning' | 'info';
export type Tier = 'deterministic' | 'forced' | 'statistical' | 'coverage';

export type AuditFinding = {
  code: string;
  severity: Severity;
  tier: Tier;
  confidence: number;
  version: string;
  uid?: number;
  verseId?: number;
  page?: number;
  imagePage?: number;
  message: string;
  evidence?: Record<string, unknown>;
  peers?: Array<Pick<GeometryRow, 'uid' | 'version' | 'verseId' | 'page' | 'imagePage'>>;
  proposedGeometry?: Partial<Pick<GeometryRow, 'X' | 'Y' | 'W' | 'H' | 'TLW' | 'TLH' | 'BRW' | 'BRH'>> | null;
  autoRepairEligible: boolean;
};

export type EditionMeta = {
  version: string;
  pages: number | null;
  pgfirstVerse: number;
  format: string;
  imageOffset: number;
};

export type FamilyDefinition = {
  id: string;
  members: string[];
  reference?: string;
};

export type PagePlacement = {
  row: GeometryRow;
  column: number;
  columnCount: number;
  columnLeft: number;
  columnRight: number;
  columnTop: number;
  columnBottom: number;
};

